<?php

/**
 * Определяет обязательные методы прямого применения и отката одной миграции.
 */

declare(strict_types=1);

namespace Otus\Autoservice\Migration;

/**
 * Контракт одной версионируемой миграции модуля.
 */
interface MigrationInterface
{
    /**
     * Возвращает уникальную возрастающую версию миграции.
     *
     * Версии сравниваются через version_compare(), поэтому должны сортироваться
     * в том же порядке, в котором изменения требуется применять.
     *
     * @return string Версия миграции, например `202608030001`.
     */
    public function getVersion(): string;

    /**
     * Применяет изменение схемы или конфигурации.
     *
     * Метод обязан либо полностью завершить изменение, либо выбросить исключение,
     * чтобы менеджер не записал миграцию как успешно выполненную.
     */
    public function up(): void;

    /**
     * Отменяет изменение при полном удалении данных модуля.
     *
     * Откат вызывается только при явном отказе администратора от сохранения данных.
     */
    public function down(): void;
}
