<?php

/**
 * Задаёт единый контракт для заменяемых источников внешних остатков запчастей.
 */

declare(strict_types=1);

namespace Otus\Autoservice\Integration\Stock;

/**
 * Получает абсолютное текущее количество товара из внешней системы.
 *
 * Реализация поставщика не должна изменять каталог Bitrix, создавать закупки или
 * журналировать секреты. Эти обязанности относятся к сервису синхронизации.
 */
interface StockProviderInterface
{
    /** Возвращает стабильный машинный код реализации поставщика. */
    public function getCode(): string;

    /**
     * Возвращает текущий абсолютный остаток переданной запчасти.
     *
     * @param StockItem $item Проверенные идентификаторы товара каталога.
     *
     * @return int Неотрицательное абсолютное количество, а не изменение остатка.
     *
     * @throws StockProviderException Если источник недоступен или вернул неверный ответ.
     */
    public function getCurrentQuantity(StockItem $item): int;
}
